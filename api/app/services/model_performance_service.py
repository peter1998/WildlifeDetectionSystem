    @staticmethod
    def _find_latest_model_path():
        """
        Helper method to find the most recent model directory.
        Returns tuple of (model_folder_name, full_path_to_model)
        """
        # Path to trained models
        models_dir = current_app.config.get('MODEL_FOLDER', 
                    os.path.join(os.path.dirname(os.path.dirname(os.path.dirname(
                    os.path.abspath(__file__)))), 'models', 'trained'))
        
        # Find all model folders by creation date
        model_folders = []
        try:
            for folder in os.listdir(models_dir):
                folder_path = os.path.join(models_dir, folder)
                if os.path.isdir(folder_path) and 'wildlife_detector' in folder:
                    creation_time = os.path.getctime(folder_path)
                    model_folders.append((folder, creation_time, folder_path))
            
            if not model_folders:
                logging.warning("No model folders found in %s", models_dir)
                return None, None
                
            # Sort by creation time (newest first)
            model_folders.sort(key=lambda x: x[1], reverse=True)
            return model_folders[0][0], model_folders[0][2]
        except Exception as e:
            logging.error("Error finding latest model path: %s", str(e))
            return None, None

    @staticmethod
    def _get_model_dir(model_id=None):
        """Get the model directory for a given model ID or the latest model."""
        if model_id:
            # Path to trained models
            models_dir = current_app.config.get('MODEL_FOLDER', 
                        os.path.join(os.path.dirname(os.path.dirname(os.path.dirname(
                        os.path.abspath(__file__)))), 'models', 'trained'))
            
            # Check if model exists
            model_path = os.path.join(models_dir, model_id)
            if os.path.exists(model_path) and os.path.isdir(model_path):
                return model_path
            return None
        else:
            # Get the latest model path
            _, model_path = ModelPerformanceService._find_latest_model_path()
            return model_path

    @staticmethod
    def _load_dashboard_file(model_dir, filename):
        """Helper to load a dashboard JSON file from model directory."""
        if not model_dir:
            return None
            
        # First check in the dashboard subdirectory (generated by notebook 4)
        dashboard_dir = os.path.join(model_dir, "dashboard")
        file_path = os.path.join(dashboard_dir, filename)
        
        if os.path.exists(file_path):
            try:
                with open(file_path, 'r') as f:
                    return json.load(f)
            except Exception as e:
                logging.error(f"Error loading dashboard file {filename}: {str(e)}")
        
        # If not found in dashboard dir, try root model dir
        file_path = os.path.join(model_dir, filename)
        if os.path.exists(file_path):
            try:
                with open(file_path, 'r') as f:
                    return json.load(f)
            except Exception as e:
                logging.error(f"Error loading model dir file {filename}: {str(e)}")
                
        return None

